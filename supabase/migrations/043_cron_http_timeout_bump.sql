-- Kay's Pay: raise cron HTTP timeout further after strengthening VTUAfrica retry
-- =====================================================================
-- Migration 042 set net.http_post's timeout to 30s (up from pg_net's 5s
-- default). Right after that, callVTUAfricaWithRetry was strengthened from
-- 3 flat 1.5s retries (~4.5s window) to 5 exponential-backoff retries (~15s
-- window) per call, after a real payroll cycle showed even 3 attempts
-- weren't enough to survive a sustained DNS blip. A payroll with more
-- recipients than RECIPIENT_CONCURRENCY (10) runs in sequential batches, so
-- worst case (every batch hitting a full 15s retry window) can now
-- comfortably exceed 30s. Bumping to 60s so a slow-but-successful run still
-- gets its result logged, instead of recreating the exact "silently
-- invisible" problem migration 042 just fixed.
-- =====================================================================

